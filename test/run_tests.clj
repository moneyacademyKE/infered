(ns run-tests
  (:require [clojure.test :refer [run-tests]]))

(println "==========================================================")
(println "⚡ RUNNING INFERED CLOUDFLARE VIRTUAL ROUTER TEST SUITE ⚡")
(println "==========================================================")

(load-file "test/catalog_test.clj")
(load-file "test/metrics_test.clj")
(load-file "test/pricing_test.clj")
(load-file "test/pareto_test.clj")
(load-file "test/client_test.clj")
(load-file "test/fallback_test.clj")
(load-file "test/security_test.clj")
(load-file "test/stream_test.clj")
(load-file "test/chase_test.clj")
(load-file "test/cache_test.clj")
(load-file "test/session_test.clj")
(load-file "test/swr_test.clj")
(load-file "test/worker_test.clj")
(load-file "test/refusal_test.clj")

(let [catalog-res (run-tests 'catalog-test)
      metrics-res (run-tests 'metrics-test)
      pricing-res (run-tests 'pricing-test)
      pareto-res  (run-tests 'pareto-test)
      client-res  (run-tests 'client-test)
      fallback-res (run-tests 'fallback-test)
      security-res (run-tests 'security-test)
      stream-res  (run-tests 'stream-test)
      chase-res   (run-tests 'chase-test)
      cache-res   (run-tests 'cache-test)
      session-res (run-tests 'session-test)
      swr-res     (run-tests 'swr-test)
      worker-res  (run-tests 'worker-test)
      refusal-res (run-tests 'refusal-test)
      total-fail  (+ (:fail catalog-res) (:fail metrics-res) (:fail pricing-res)
                     (:fail pareto-res) (:fail client-res) (:fail fallback-res) (:fail security-res)
                     (:fail stream-res) (:fail chase-res)
                     (:fail cache-res) (:fail session-res) (:fail swr-res) (:fail worker-res)
                     (:fail refusal-res))
      total-err   (+ (:error catalog-res) (:error metrics-res) (:error pricing-res)
                     (:error pareto-res) (:error client-res) (:error fallback-res) (:error security-res)
                     (:error stream-res) (:error chase-res)
                     (:error cache-res) (:error session-res) (:error swr-res) (:error worker-res)
                     (:error refusal-res))]
  (println "\n----------------------------------------------------------")
  (if (and (zero? total-fail) (zero? total-err))
    (do
      (println "✅ ALL TESTS PASSED SUCCESSFULLY! (Rich Hickey Quality Certified)")
      (println "----------------------------------------------------------\n"))
    (do
      (println (str "❌ TEST SUITE FAILED: " total-fail " failures, " total-err " errors"))
      (println "----------------------------------------------------------\n")
      (System/exit 1))))
